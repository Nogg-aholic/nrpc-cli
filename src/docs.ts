		"  executionPurity: 'pure' | 'impure' | 'unknown';",
		'  reason: string;',
		'};',
		'',
		"type OpenApiMemberAbiFlags = {",
		'  static: boolean;',
		'  async: boolean;',
		'  readonly: boolean;',
		'  abstract: boolean;',
		"  visibility: 'public' | 'protected' | 'private';",
		'  override: boolean;',
		'  deprecated: boolean;',
		'  export: boolean;',
		'};',

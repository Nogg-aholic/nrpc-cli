		'  }',
		'',
		'  return {',
		'    status: 200,',
		"    kind: 'html',",
		'    body: renderScalarHtml(document, {',
		'      pageTitle: options.buildMethodTitle?.(options.routeMethodName) ?? options.routeMethodName,',

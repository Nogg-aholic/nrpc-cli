		'  }',
		'',
		"  const docsHtmlPath = `${trimTrailingSlash(options.namespacePath)}/__docs/scalar`;",
		'  if (options.requestUrl.pathname === docsHtmlPath) {',
		'    return {',
		'      status: 200,',
		"      kind: 'html',",
		'      body: options.artifacts.html,',
